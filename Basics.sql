/*------------------------------------------------------------
Question 1
--------------------------------------------------------------
Retrieve all employees from the Employees table.
------------------------------------------------------------*/

SELECT *
FROM Employees;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns all columns and all rows from the Employees table.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Avoid using SELECT * in production unless all columns are
required.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 2
--------------------------------------------------------------
Retrieve EmployeeName, Department and Salary.
------------------------------------------------------------*/

SELECT EmployeeName,
       Department,
       Salary
FROM Employees;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns only the required columns instead of every column.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Selecting only the required columns improves readability
and performance.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 3
--------------------------------------------------------------
Retrieve employees whose salary is greater than ₹50,000.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE Salary > 50000;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees whose salary exceeds ₹50,000.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Filter rows as early as possible using the WHERE clause.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 4
--------------------------------------------------------------
Retrieve employees working in the IT department.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE Department = 'IT';

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees belonging to the IT department.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Character values should always be enclosed in single quotes.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 5
--------------------------------------------------------------
Retrieve employees whose salary is between ₹40,000 and ₹80,000.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE Salary BETWEEN 40000 AND 80000;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees whose salary falls within the specified
range (inclusive).
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
BETWEEN includes both the lower and upper boundary values.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 6
--------------------------------------------------------------
Retrieve employees whose names start with 'A'.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE EmployeeName LIKE 'A%';

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees whose names begin with the letter A.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
The % wildcard represents zero or more characters.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 7
--------------------------------------------------------------
Retrieve employees working in the IT or HR departments.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE Department IN ('IT', 'HR');

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees belonging to either the IT or HR
department.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Use IN instead of multiple OR conditions for cleaner SQL.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 8
--------------------------------------------------------------
Display all employees ordered by salary in descending order.
------------------------------------------------------------*/

SELECT *
FROM Employees
ORDER BY Salary DESC;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Sorts employees from the highest salary to the lowest.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
DESC sorts in descending order while ASC sorts in ascending
order.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 9
--------------------------------------------------------------
Display the top five highest-paid employees.
------------------------------------------------------------*/

SELECT *
FROM Employees
ORDER BY Salary DESC
LIMIT 5;

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns the five employees with the highest salaries.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
LIMIT syntax works in MySQL and PostgreSQL. SQL Server uses
TOP and Oracle uses FETCH FIRST.
------------------------------------------------------------*/



/*------------------------------------------------------------
Question 10
--------------------------------------------------------------
Retrieve employees hired after 1 January 2023.
------------------------------------------------------------*/

SELECT *
FROM Employees
WHERE HireDate > '2023-01-01';

/*------------------------------------------------------------
Explanation
--------------------------------------------------------------
Returns employees hired after 1 January 2023.
------------------------------------------------------------*/

/*------------------------------------------------------------
Interview Tip
--------------------------------------------------------------
Use the ISO date format (YYYY-MM-DD) for better portability
across SQL databases.
------------------------------------------------------------*/
